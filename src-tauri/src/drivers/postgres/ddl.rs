//! `CREATE` statements built from the catalogue, so there is no `pg_dump` dependency. The
//! rendering is pure (and unit-tested); `introspect::ddl` fills the structs from the catalogue.

/// Always quote: correct for every identifier, including reserved words and mixed case.
pub fn quote(ident: &str) -> String {
    format!("\"{}\"", ident.replace('"', "\"\""))
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnDef {
    pub name: String,
    pub type_name: String,
    pub not_null: bool,
    pub default: Option<String>,
    /// `a` = `GENERATED ALWAYS AS IDENTITY`, `d` = `GENERATED BY DEFAULT AS IDENTITY`.
    pub identity: Option<char>,
    /// `s` = `GENERATED ALWAYS AS (default) STORED`.
    pub generated: Option<char>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableDef {
    pub schema: String,
    pub name: String,
    pub columns: Vec<ColumnDef>,
    /// `(constraint name, definition)` in dump order: primary key, unique, check, foreign keys.
    pub constraints: Vec<(String, String)>,
    /// Full `CREATE [UNIQUE] INDEX ...` statements for indexes that back no constraint.
    pub indexes: Vec<String>,
}

fn column_sql(c: &ColumnDef) -> String {
    let mut s = format!("{} {}", quote(&c.name), c.type_name);
    match (c.generated, c.identity, &c.default) {
        (Some('s'), _, Some(expr)) => s.push_str(&format!(" GENERATED ALWAYS AS ({expr}) STORED")),
        (_, Some('a'), _) => s.push_str(" GENERATED ALWAYS AS IDENTITY"),
        (_, Some('d'), _) => s.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
        (_, _, Some(expr)) => s.push_str(&format!(" DEFAULT {expr}")),
        _ => {}
    }
    if c.not_null {
        s.push_str(" NOT NULL");
    }
    s
}

pub fn render_table(t: &TableDef) -> String {
    let mut lines: Vec<String> = t.columns.iter().map(column_sql).collect();
    lines.extend(
        t.constraints
            .iter()
            .map(|(name, def)| format!("CONSTRAINT {} {def}", quote(name))),
    );
    let mut out = format!(
        "CREATE TABLE {}.{} (\n    {}\n);",
        quote(&t.schema),
        quote(&t.name),
        lines.join(",\n    ")
    );
    for ix in &t.indexes {
        out.push_str("\n\n");
        out.push_str(ix);
        out.push(';');
    }
    out
}

pub fn render_view(
    schema: &str,
    name: &str,
    definition: &str,
    materialized: bool,
    indexes: &[String],
) -> String {
    let body = definition.trim().trim_end_matches(';');
    let head = if materialized {
        "CREATE MATERIALIZED VIEW"
    } else {
        "CREATE OR REPLACE VIEW"
    };
    let mut out = format!("{head} {}.{} AS\n{body};", quote(schema), quote(name));
    for ix in indexes {
        out.push_str("\n\n");
        out.push_str(ix);
        out.push(';');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, ty: &str, not_null: bool) -> ColumnDef {
        ColumnDef {
            name: name.into(),
            type_name: ty.into(),
            not_null,
            default: None,
            identity: None,
            generated: None,
        }
    }

    /// The fixture table of `tests/fixtures/pg_ddl_orders.sql`, as the catalogue reports it.
    fn orders() -> TableDef {
        TableDef {
            schema: "public".into(),
            name: "orders".into(),
            columns: vec![
                ColumnDef {
                    identity: Some('a'),
                    ..col("id", "bigint", true)
                },
                col("user_id", "bigint", true),
                ColumnDef {
                    default: Some("'new'::order_status".into()),
                    ..col("status", "order_status", true)
                },
                ColumnDef {
                    default: Some("0".into()),
                    ..col("total", "numeric(12,2)", false)
                },
                ColumnDef {
                    default: Some("(total * (2)::numeric)".into()),
                    generated: Some('s'),
                    ..col("double_total", "numeric", false)
                },
            ],
            constraints: vec![
                ("orders_pkey".into(), "PRIMARY KEY (id)".into()),
                (
                    "orders_total_check".into(),
                    "CHECK ((total >= (0)::numeric))".into(),
                ),
                (
                    "orders_user_id_fkey".into(),
                    "FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE".into(),
                ),
            ],
            indexes: vec![
                "CREATE INDEX orders_user_id_idx ON public.orders USING btree (user_id)".into(),
            ],
        }
    }

    #[test]
    fn a_table_renders_columns_constraints_and_indexes_in_dump_order() {
        let golden = include_str!("../../../tests/fixtures/pg_ddl_orders.golden.sql");
        assert_eq!(render_table(&orders()), golden.trim_end());
    }

    #[test]
    fn identifiers_are_always_quoted_and_escaped() {
        assert_eq!(quote("Order Items"), "\"Order Items\"");
        assert_eq!(quote("a\"b"), "\"a\"\"b\"");
        let t = TableDef {
            schema: "My Schema".into(),
            name: "t".into(),
            columns: vec![col("select", "text", false)],
            constraints: vec![],
            indexes: vec![],
        };
        assert_eq!(
            render_table(&t),
            "CREATE TABLE \"My Schema\".\"t\" (\n    \"select\" text\n);"
        );
    }

    #[test]
    fn views_and_materialized_views() {
        assert_eq!(
            render_view("public", "v", " SELECT 1 AS one;\n", false, &[]),
            "CREATE OR REPLACE VIEW \"public\".\"v\" AS\nSELECT 1 AS one;"
        );
        assert_eq!(
            render_view(
                "public",
                "m",
                "SELECT 1 AS one",
                true,
                &["CREATE INDEX m_idx ON public.m USING btree (one)".into()]
            ),
            "CREATE MATERIALIZED VIEW \"public\".\"m\" AS\nSELECT 1 AS one;\n\nCREATE INDEX m_idx ON public.m USING btree (one);"
        );
    }
}
