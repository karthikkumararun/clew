// Generate docs/qa/checklist.md: every scenario of the finished capabilities that has no
// end-to-end test (or is marked `<!-- manual -->` in its spec), plus the fixed manual checks
// (spec: release-qa › Manual QA checklist).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import {
  collectDeclarations,
  computeCoverage,
  indexSpecs,
  scenarioKey,
  needsRealRender,
  type Coverage,
  type Scenario,
  type SpecIndex,
} from "./check-scenario-coverage";

/** Checks no automated test can make: they need a person and real systems. */
export const FIXED_MANUAL_CHECKS: { title: string; steps: string[] }[] = [
  {
    title: "Visual fidelity against the canvas screens",
    steps: [
      "Open each screen next to its canvas in `design/canvas/` (and the exported PNG in `design/screens/`)",
      "Compare layout, spacing, colour, copy and states; list differences as defects",
    ],
  },
  {
    title: "Native file and folder dialogs",
    steps: [
      "Use Open database file, Export, Import, Save script and Choose folder on this OS",
      "Each opens the platform's own dialog, remembers the last folder and returns the chosen path",
    ],
  },
  {
    title: "Oracle Instant Client missing and found",
    steps: [
      "Connect to Oracle with no Instant Client installed: the app explains what is missing and where to get it",
      "Install it and connect again: the connection works without restarting the app",
    ],
  },
  {
    title: "GitHub Copilot sign-in",
    steps: [
      "Start the Copilot sign-in from the AI settings and complete the device flow",
      "Sign out: the token is removed from the keychain and the assistant stops using Copilot",
    ],
  },
  {
    title: "macOS Gatekeeper and Windows SmartScreen",
    steps: [
      "Install from the release artifact on a clean machine",
      "Gatekeeper (notarized) or SmartScreen (signed) lets the user open it without workarounds",
    ],
  },
  {
    title: "Accessibility with a screen reader",
    steps: [
      "With VoiceOver (macOS) or NVDA (Windows): connect, run a query, read a result, open and close a dialog",
      "Every control has a name, focus order is logical and dialogs trap and restore focus",
    ],
  },
];

/** Scenarios that are not covered by an end-to-end test (or are marked manual). */
export function manualScenarios(index: SpecIndex, coverage: Coverage): Scenario[] {
  return index.scenarios.filter((s) => {
    if (s.status !== "finished") return false;
    const levels = coverage.byScenario.get(scenarioKey(s));
    return s.manual || !levels?.has("e2e");
  });
}

/**
 * Whether a person has to look: the scenario is marked manual, has no test at all, or is about
 * layout, visibility or colour and was only checked where nothing is drawn. The rest is covered
 * by unit or integration tests and only needs a spot check if there is time.
 */
export function needsAPerson(s: Scenario, coverage: Coverage): boolean {
  const levels = coverage.byScenario.get(scenarioKey(s));
  return s.manual || !levels || needsRealRender(s, levels);
}

export function renderChecklist(index: SpecIndex, coverage: Coverage): string {
  const all = manualScenarios(index, coverage);
  const person = all.filter((s) => needsAPerson(s, coverage));
  const below = all.filter((s) => !needsAPerson(s, coverage));
  const lines: string[] = [
    "# Manual QA checklist",
    "",
    "Generated by `pnpm qa:checklist`. Do not edit by hand: copy it to",
    "`docs/qa/runs/<date>-<platform>.md`, fill in the header and tick the boxes there.",
    "",
    "- Build (version and commit):",
    "- OS and version:",
    "- Tester:",
    "",
    "## Fixed manual checks",
    "",
  ];
  for (const c of FIXED_MANUAL_CHECKS) {
    lines.push(`- [ ] **${c.title}**`, ...c.steps.map((s) => `  - ${s}`));
  }
  lines.push(
    "",
    `## Scenarios a person has to check (${person.length})`,
    "",
    "Marked manual, without any test, or about layout and colour with no real-render test.",
    "",
  );
  const caps = [...new Set(person.map((s) => s.capability))].sort();
  for (const cap of caps) {
    lines.push(`### ${cap}`, "");
    for (const s of person.filter((x) => x.capability === cap)) {
      const levels = coverage.byScenario.get(scenarioKey(s));
      const note = s.manual
        ? " _(manual)_"
        : levels
          ? ` _(only ${[...levels].join(", ")}: check how it looks)_`
          : "";
      lines.push(
        `- [ ] **${s.name}**${note} — ${s.requirement}`,
        ...s.steps.map((t) => `  - ${t}`),
      );
    }
    lines.push("");
  }
  lines.push(
    `## Covered by unit or integration tests only (${below.length})`,
    "",
    "No end-to-end test, but a test below the UI checks each one. Spot-check any you doubt; a",
    "failure here is a defect like any other.",
    "",
  );
  for (const cap of [...new Set(below.map((s) => s.capability))].sort()) {
    lines.push(`### ${cap}`, "");
    for (const s of below.filter((x) => x.capability === cap)) {
      const levels = coverage.byScenario.get(scenarioKey(s));
      lines.push(`- ${s.name} — ${s.requirement} _(${[...(levels ?? [])].join(", ")})_`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

function main(): number {
  const root = resolve(".");
  const index = indexSpecs(root);
  const coverage = computeCoverage(index, collectDeclarations(root));
  const file = resolve(root, "docs", "qa", "checklist.md");
  mkdirSync(dirname(file), { recursive: true });
  mkdirSync(resolve(root, "docs", "qa", "runs"), { recursive: true });
  writeFileSync(file, renderChecklist(index, coverage));
  const all = manualScenarios(index, coverage);
  const person = all.filter((s) => needsAPerson(s, coverage)).length;
  console.log(
    `${person} scenarios for a person, ${all.length - person} covered below the UI: docs/qa/checklist.md`,
  );
  return 0;
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  process.exit(main());
}
